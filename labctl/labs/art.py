GAP = 2  # 企鵝和道具之間空幾格
_BLOCKS = {(True, True): "█", (True, False): "▀", (False, True): "▄", (False, False): " "}


def _rows(grid):
    rows = grid.strip("\n").split("\n")
    width = max(len(row) for row in rows)
    return [row.ljust(width, ".") for row in rows]


def render_grid(grid):
    """把格子轉成半格方塊，一格一個字元、上下兩格一行，回傳去掉行尾空白的每一行。"""
    rows = _rows(grid)
    if len(rows) % 2:
        rows.append("." * len(rows[0]))
    return [
        ("".join(_BLOCKS[(top == "#", bottom == "#")] for top, bottom in zip(upper, lower, strict=True))).rstrip()
        for upper, lower in zip(rows[0::2], rows[1::2], strict=True)
    ]


def render(lab_id):
    """該題的點陣圖，結尾有換行。沒有圖的題目（Lab 08）丟 KeyError。"""
    penguin, item = _rows(PENGUIN), _rows(PROPS[lab_id])
    top = len(penguin) - len(item)
    blank = "." * len(item[0])
    composed = [row + "." * GAP + (item[i - top] if i >= top else blank) for i, row in enumerate(penguin)]
    return "\n".join(render_grid("\n".join(composed))) + "\n"
